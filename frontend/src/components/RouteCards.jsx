import { LEVELS, UNKNOWN } from "../lib/risk";
import { fmtDateTime, fmtDuration, fmtMiles, ROUTE_COLORS } from "../lib/format";

// null = no known weather on the route; never present that as 0 (safe)
const fmtAvg = (v) => (v == null ? "—" : v.toFixed(2));

const KEY_TEXT = {
  no_travel_miles: ["fewer No Travel miles", (r) => fmtMiles(r.summary.miles_by_level.no_travel)],
  unknown_miles: ["fewer miles without a forecast", (r) => fmtMiles(r.summary.miles_by_level.unknown)],
  severe_miles: ["fewer Severe miles", (r) => fmtMiles(r.summary.miles_by_level.severe)],
  high_miles: ["fewer High miles", (r) => fmtMiles(r.summary.miles_by_level.high)],
  avg_risk: ["lower average risk", (r) => fmtAvg(r.summary.avg_risk)],
  travel_time: ["shorter travel time", (r) => fmtDuration(r.elapsed_s)],
};

export function Recommendation({ plan }) {
  const rec = plan.recommendation;
  const byId = Object.fromEntries(plan.routes.map((r) => [r.id, r]));
  const best = byId[rec.route_id];
  const fastest = plan.routes.reduce((a, b) => (b.elapsed_s < a.elapsed_s ? b : a));
  const slower = best.elapsed_s - fastest.elapsed_s;

  let why = null;
  if (rec.deciding_key) {
    const [text, value] = KEY_TEXT[rec.deciding_key];
    const runner = byId[rec.runner_up_id];
    why = <>Wins on <b>{text}</b>: {value(best)} vs {value(runner)} on Route {runner.id}.</>;
  }

  return (
    <div className={`card recommend ${rec.all_no_travel ? "danger" : ""}`}>
      <div className="card-pad">
        {rec.all_no_travel ? (
          <>
            <div className="rec-title">⛔ No safe route at this departure time</div>
            <p>Every option crosses No Travel weather. Route {best.id} is the least bad; consider
              delaying departure (scrub the forecast slider to see when it clears).</p>
          </>
        ) : (
          <>
            <div className="rec-title">
              <span className="swatch" style={{ background: ROUTE_COLORS[best.id] }} />
              Recommended: Route {best.id}
            </div>
            <p>{why ?? "Only one route is available."}</p>
            <p className="muted">
              {slower > 60 ? `${fmtDuration(slower)} slower than the fastest route.` : "Also the fastest option."}
              {" "}Arrives {fmtDateTime(best.arrival)}.
            </p>
          </>
        )}
        {rec.has_unknown && (
          <p className="warn">Some checkpoints have no forecast (Unknown) and are not counted as safe.</p>
        )}
      </div>
    </div>
  );
}

export default function RouteCards({ plan, selected, onSelect }) {
  const rank = Object.fromEntries(plan.recommendation.ranking.map((id, i) => [id, i + 1]));
  return (
    <div className="route-cards">
      {plan.routes.map((r) => {
        const miles = r.summary.miles_by_level;
        const recommended = r.id === plan.recommendation.route_id && !plan.recommendation.all_no_travel;
        return (
          <button
            key={r.id}
            className={`card route-card ${selected === r.id ? "selected" : ""}`}
            onClick={() => onSelect(selected === r.id ? null : r.id)}
            style={{ "--route": ROUTE_COLORS[r.id] }}
          >
            <div className="rc-head">
              <span className="route-badge">{r.id}</span>
              <span className="rc-rank">#{rank[r.id]}</span>
              {recommended && <span className="pill good">Recommended</span>}
              {miles.no_travel > 0 && <span className="pill bad">No Travel</span>}
              {r.generated_detour && <span className="pill" title="Generated by forcing a detour; the routing API returned fewer than 3 options">Detour</span>}
            </div>
            <div className="rc-stats">
              <div><span>{fmtMiles(r.distance_mi)}</span><small>distance</small></div>
              <div><span>{fmtDuration(r.elapsed_s)}</span><small>{r.rest_stops.length ? `incl. ${r.rest_stops.length} rest${r.rest_stops.length > 1 ? "s" : ""}` : "travel time"}</small></div>
              <div><span>{fmtAvg(r.summary.avg_risk)}</span><small>avg risk</small></div>
            </div>
            <div className="risk-bar" aria-label="Miles by risk level">
              {[...LEVELS, UNKNOWN].map((l) =>
                miles[l.key] > 0 ? (
                  <span key={l.key} style={{ flex: miles[l.key], background: l.color }}
                    title={`${l.label}: ${fmtMiles(miles[l.key])}`} />
                ) : null,
              )}
            </div>
            <div className="risk-miles">
              {[...LEVELS, UNKNOWN].filter((l) => miles[l.key] > 0).map((l) => (
                <span key={l.key}><i style={{ background: l.color }} />{l.label} {fmtMiles(miles[l.key])}</span>
              ))}
            </div>
          </button>
        );
      })}
    </div>
  );
}
